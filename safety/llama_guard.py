
"""
ZENTIQ - Llama Guard Safety Module

Uses Llama Guard 3:1B through Ollama to screen
incoming user messages and outgoing AI responses.

Developed by EverMark Creative Solutions.
"""

from ai_engine.ollama_client import OllamaClient


class LlamaGuard:

    def __init__(
        self,
        ollama_client=None,
        guard_model="llama-guard3:1b"
    ):
        self.ollama_client = ollama_client or OllamaClient()
        self.guard_model = guard_model

    def check_connection(self):
        """Check whether Ollama and the guard model are available."""

        try:
            if not self.ollama_client.check_connection():
                return False

            models = self.ollama_client.list_models()

            return any(
                model == self.guard_model
                or model.startswith(self.guard_model + "-")
                for model in models
            )

        except Exception:
            return False

    def _classify(self, content, role):
        """Classify content using Llama Guard."""

        if not isinstance(content, str) or not content.strip():
            return {
                "safe": False,
                "label": "error",
                "reason": "Empty content cannot be screened."
            }

        if role not in ("user", "assistant"):
            raise ValueError("Role must be user or assistant.")

        if not self.check_connection():
            return {
                "safe": False,
                "label": "error",
                "reason": "Llama Guard or its model is unavailable."
            }

        guard_prompt = f"""
[INST] Task: Check if there is unsafe content in
'{role}' messages in a conversation.

<BEGIN UNSAFE CONTENT>
{content}
<END UNSAFE CONTENT>

Provide your safety assessment.
Your first line must be either safe or unsafe.
If unsafe, provide the relevant safety category.
[/INST]
"""

        try:
            result = self.ollama_client.generate(
                prompt=guard_prompt,
                model=self.guard_model,
                temperature=0.0
            )

            if not result:
                raise ValueError("Llama Guard returned an empty result.")

            first_line = result.strip().splitlines()[0].strip().lower()

            if first_line == "safe":
                return {
                    "safe": True,
                    "label": "safe",
                    "reason": "Content passed Llama Guard screening."
                }

            if first_line.startswith("unsafe"):
                return {
                    "safe": False,
                    "label": "unsafe",
                    "reason": result.strip()
                }

            raise ValueError(
                f"Unexpected Llama Guard response: {result}"
            )

        except Exception as error:
            return {
                "safe": False,
                "label": "error",
                "reason": f"Safety screening failed: {error}"
            }

    def check_input(self, user_message):
        """Screen a message submitted by the user."""

        return self._classify(
            content=user_message,
            role="user"
        )

    def check_output(self, assistant_response):
        """Screen a response generated by an AI provider."""

        return self._classify(
            content=assistant_response,
            role="assistant"
              )
      
